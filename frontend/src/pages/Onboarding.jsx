import { useEffect, useState } from "react";
import { Link } from "react-router-dom";
import { CheckCircle2, ShieldAlert } from "lucide-react";
import { useBank } from "../context/BankContext";
import { useTxRunner } from "../hooks/useTxRunner";
import { formatDateTime } from "../lib/format";
import { RequireChain } from "../components/StatusGuards";
import TxStatusPanel from "../components/TxStatusPanel";
import { Button, PageHeader, Spinner } from "../components/ui";

function Step({ number, title, done, children }) {
  return (
    <div className={`card p-5 ${done ? "bg-slate-50/60" : ""}`}>
      <div className="flex items-start gap-4">
        <span
          className={`flex size-8 shrink-0 items-center justify-center rounded-full text-sm font-semibold ${
            done ? "bg-emerald-100 text-emerald-700" : "bg-brand-600 text-white"
          }`}
        >
          {done ? <CheckCircle2 className="size-4.5" /> : number}
        </span>
        <div className="min-w-0 flex-1">
          <h2 className="text-sm font-semibold text-slate-900">{title}</h2>
          <div className="mt-2">{children}</div>
        </div>
      </div>
    </div>
  );
}

function OnboardingContent() {
  const { profile, isAdmin, activeLabel, activeAddress } = useBank();
  const { tx, run, reset, busy } = useTxRunner();
  const [name, setName] = useState("");

  useEffect(() => setName(activeLabel && activeLabel !== "Administrator" ? activeLabel : ""), [activeLabel, activeAddress]);
  useEffect(() => reset(), [activeAddress, reset]);

  if (isAdmin) {
    return (
      <div className="card mx-auto max-w-xl p-8 text-center">
        <ShieldAlert className="mx-auto size-8 text-brand-600" />
        <h2 className="mt-3 text-lg font-semibold text-slate-900">Administrator account selected</h2>
        <p className="mt-2 text-sm text-slate-600">
          Select a new customer (for example <strong>Diana Karim</strong>) from the account menu to demonstrate registration.
        </p>
      </div>
    );
  }
  if (!profile.loaded) return <Spinner />;

  const trimmed = name.trim();
  const nameBytes = new TextEncoder().encode(trimmed).length;
  const nameError = trimmed && nameBytes > 64 ? "Name must be at most 64 bytes." : null;

  return (
    <div className="mx-auto max-w-2xl space-y-4">
      <Step number={1} title="Register as a customer" done={profile.registered}>
        {profile.registered ? (
          <p className="text-sm text-slate-600">
            Registered as <strong className="text-slate-900">{profile.name}</strong> · Customer #{profile.customerId.toString()} ·{" "}
            {formatDateTime(profile.registeredAt)}
          </p>
        ) : (
          <form
            onSubmit={(e) => {
              e.preventDefault();
              run("Customer registration", (c) => c.registerCustomer(trimmed));
            }}
            className="space-y-3"
          >
            <p className="text-sm text-slate-600">
              Links your wallet address <span className="mono text-slate-800">{activeAddress}</span> to a customer record. Only a
              display name is stored — no sensitive personal data.
            </p>
            <div>
              <label className="label" htmlFor="name">
                Display name
              </label>
              <input id="name" className="input" value={name} onChange={(e) => setName(e.target.value)} placeholder="e.g. Diana Karim" maxLength={80} />
              {nameError && <p className="mt-1 text-xs text-red-600">{nameError}</p>}
            </div>
            <Button type="submit" loading={busy} disabled={!trimmed || Boolean(nameError)}>
              Register customer
            </Button>
          </form>
        )}
      </Step>

      <Step number={2} title="Open a banking account" done={profile.hasAccount}>
        {profile.hasAccount ? (
          <p className="text-sm text-slate-600">
            Account <strong className="text-slate-900 tabular-nums">{profile.accountNumber.toString()}</strong> opened{" "}
            {formatDateTime(profile.createdAt)}.
          </p>
        ) : (
          <div className="space-y-3">
            <p className="text-sm text-slate-600">
              Creates an active account with a zero balance and a unique account number generated by the contract.
            </p>
            <Button onClick={() => run("Account creation", (c) => c.createAccount())} loading={busy} disabled={!profile.registered}>
              Open account
            </Button>
          </div>
        )}
      </Step>

      {profile.registered && profile.hasAccount && (
        <div className="card flex flex-wrap items-center justify-between gap-3 p-5">
          <p className="text-sm text-slate-700">Onboarding complete. Your account is ready.</p>
          <div className="flex gap-2">
            <Link to="/deposit">
              <Button>Make a deposit</Button>
            </Link>
            <Link to="/app">
              <Button variant="secondary">Go to dashboard</Button>
            </Link>
          </div>
        </div>
      )}

      <TxStatusPanel tx={tx} onReset={reset} />
    </div>
  );
}

export default function Onboarding() {
  return (
    <>
      <PageHeader title="Customer onboarding" description="Register the selected wallet address and open a SecureBank account." />
      <RequireChain>
        <OnboardingContent />
      </RequireChain>
    </>
  );
}
